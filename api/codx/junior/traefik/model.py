"""
Pydantic model for user-defined Traefik rules.

A rule is stored inside the settings object that owns it (global settings or a
project's ``.codx/project.json``), so it does not need a ``scope`` field.  The
API and UI add the scope when a rule is rendered.

Target types
------------
``url``
    A full ``http://`` / ``https://`` URL.  Traefik forwards to it through a
    generated load-balancer service.
``workspace_app``
    A ``WorkspaceApp``.  The generated router reuses the service already
    created by the workspace labels (``<router-id>@docker``) or, for
    external-URL apps, the HTTP-provider service.
``container``
    A running Docker container and an internal port.  The generated URL is
    ``http://<container-name>:<port>``.
"""

from enum import Enum
from typing import List, Optional

from pydantic import BaseModel, Field, field_validator


class TraefikTargetType(str, Enum):
    """How a custom rule reaches its backend."""

    URL = "url"
    WORKSPACE_APP = "workspace_app"
    CONTAINER = "container"


class TraefikRule(BaseModel):
    """A user-defined Traefik router + service definition."""

    id: str = Field(
        default="",
        description=(
            "Stable rule id. Generated by the UI/API when blank; it is only "
            "unique inside its storage (global or one project)."
        ),
    )
    name: str = Field(default="", description="Display name")
    description: str = Field(default="")
    enabled: bool = Field(default=True, description="Publish this rule to Traefik")

    target_type: TraefikTargetType = Field(
        default=TraefikTargetType.URL,
        description="url | workspace_app | container",
    )
    url: str = Field(default="", description="Target URL for target_type=url")
    workspace_slug: str = Field(
        default="",
        description="Workspace folder_path for target_type=workspace_app",
    )
    app_id: str = Field(
        default="",
        description=(
            "Workspace app key (app.id or the name-based key used by the "
            "workspace labels) for target_type=workspace_app"
        ),
    )
    container_name: str = Field(
        default="", description="Docker container name for target_type=container"
    )
    container_port: Optional[int] = Field(
        default=None, description="Internal container port for target_type=container"
    )

    rule: str = Field(
        default="",
        description=(
            "Traefik rule expression, e.g. "
            "Host(`app.example.com`) && PathPrefix(`/app`)"
        ),
    )
    path_prefix: str = Field(
        default="",
        description=(
            "Public path prefix used by strip_prefix. When blank it is derived "
            "from the rule expression or the target."
        ),
    )

    entrypoints: List[str] = Field(
        default_factory=lambda: ["web", "websecure"],
        description="Traefik entrypoints; an empty list means Traefik's default",
    )
    middlewares: List[str] = Field(
        default_factory=list,
        description="Extra middleware names appended to the generated chain",
    )
    auth: bool = Field(
        default=True, description="Add the codx-junior auth middleware"
    )
    strip_prefix: bool = Field(
        default=False,
        description="Generate a replacePathRegex middleware for path_prefix",
    )
    priority: Optional[int] = Field(
        default=None, description="Optional Traefik router priority"
    )

    created_at: Optional[str] = Field(default=None)
    updated_at: Optional[str] = Field(default=None)

    @field_validator("entrypoints", "middlewares", mode="before")
    @classmethod
    def _coerce_string_list(cls, value):
        """Accept a comma-separated string from older/hand-edited payloads."""
        if value in (None, ""):
            return []
        if isinstance(value, str):
            return [part.strip() for part in value.split(",") if part.strip()]
        return list(value)

    @field_validator("container_port", mode="before")
    @classmethod
    def _coerce_port(cls, value):
        if value in ("", None):
            return None
        return int(value)

    @field_validator("priority", mode="before")
    @classmethod
    def _coerce_priority(cls, value):
        if value in ("", None):
            return None
        return int(value)

    @field_validator("target_type", mode="before")
    @classmethod
    def _coerce_target_type(cls, value):
        if value in (None, ""):
            return TraefikTargetType.URL
        return value

    @field_validator("path_prefix")
    @classmethod
    def _normalise_path_prefix(cls, value: str) -> str:
        """Keep a leading slash, drop a trailing one (``/`` stays ``/``)."""
        value = (value or "").strip()
        if not value:
            return ""
        if not value.startswith("/"):
            value = "/" + value
        if len(value) > 1:
            value = value.rstrip("/")
        return value
