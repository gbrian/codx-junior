# ── Host registry ──────────────────────────────────────────────────────────────


@dataclass
class InfraHostConfig:
    """Static description of a Docker endpoint."""

    id: str
    name: str
    endpoint: str
    is_local: bool = False


def _parse_hosts_env() -> List[InfraHostConfig]:
    """
    Read ``CODX_JUNIOR_INFRA_HOSTS`` (JSON array of host definitions).

    Expected shape::

        [{"id": "host-local", "name": "my-host",
          "endpoint": "unix:///var/run/docker.sock", "is_local": true}]

    Returns:
        The parsed hosts, or an empty list when unset/invalid.
    """
    raw = (os.environ.get("CODX_JUNIOR_INFRA_HOSTS") or "").strip()
    if not raw:
        return []

    try:
        entries = json.loads(raw)
    except ValueError:
        logger.error("CODX_JUNIOR_INFRA_HOSTS is not valid JSON, ignoring it")
        return []

    if not isinstance(entries, list):
        logger.error("CODX_JUNIOR_INFRA_HOSTS must be a JSON array, ignoring it")
        return []

    hosts: List[InfraHostConfig] = []
    for index, entry in enumerate(entries):
        if not isinstance(entry, dict):
            logger.warning("Skipping invalid infra host entry #%d", index)
            continue
        endpoint = str(entry.get("endpoint") or DEFAULT_ENDPOINT)
        hosts.append(
            InfraHostConfig(
                id=str(entry.get("id") or f"host-{index}"),
                name=str(entry.get("name") or entry.get("id") or f"host-{index}"),
                endpoint=endpoint,
                is_local=bool(entry.get("is_local", _is_local_endpoint(endpoint))),
            )
        )
    return hosts


def _is_local_endpoint(endpoint: str) -> bool:
    """Return True when the endpoint points at the local daemon socket."""
    return endpoint.startswith("unix://") or endpoint.startswith("/")


def _default_hosts() -> List[InfraHostConfig]:
    """Hosts from the environment, or a single local-daemon host."""
    configured = _parse_hosts_env()
    if configured:
        return configured
    return [
        InfraHostConfig(
            id=LOCAL_HOST_ID,
            name=socket.gethostname() or LOCAL_HOST_ID,
            endpoint=DEFAULT_ENDPOINT,
            is_local=True,
        )
    ]


# ── Formatting helpers ────────────────────────────────────────────────────────


def _iso(value: Any) -> str:
    """
    Normalise a Docker timestamp to ISO 8601 UTC.

    Docker mixes formats: unix seconds (container/image lists), ISO strings
    with nanosecond precision (``State.StartedAt``) and its zero-time
    (``0001-01-01T00:00:00Z``, mapped to an empty string).
    """
    if value in (None, "", 0):
        return ""

    if isinstance(value, (int, float)):
        return datetime.fromtimestamp(float(value), tz=timezone.utc).isoformat()

    text = ISO_FRACTION_RE.sub(r"\1", str(value)).replace("Z", "+00:00")
    try:
        parsed = datetime.fromisoformat(text)
    except ValueError:
        return ""

    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=timezone.utc)
    if parsed.year < 1970:
        return ""
    return parsed.astimezone(timezone.utc).isoformat()


def _fmt_duration(seconds: int) -> str:
    """Render a duration like docker does (``3d 4h``, ``12m``, ``9s``)."""
    seconds = max(0, int(seconds or 0))
    days, remainder = divmod(seconds, 86400)
    hours, remainder = divmod(remainder, 3600)
    minutes = remainder // 60
    if days:
        return f"{days}d {hours}h"
    if hours:
        return f"{hours}h {minutes}m"
    if minutes:
        return f"{minutes}m"
    return f"{seconds}s"


def _status_text(state: str, uptime_seconds: int, exit_code: Optional[int] = None) -> str:
    """Build a ``docker ps``-like status line from the container state."""
    if state == "running":
        return f"Up {_fmt_duration(uptime_seconds)}"
    if state == "paused":
        return f"Up {_fmt_duration(uptime_seconds)} (Paused)"
    if state == "restarting":
        return "Restarting"
    if state == "exited":
        return f"Exited ({exit_code})" if exit_code is not None else "Exited"
    return state.capitalize() if state else ""


def _uptime_from_status(status_text: str) -> int:
    """Approximate uptime in seconds from a ``docker ps`` STATUS string."""
    match = re.search(
        r"Up\s+(?:About\s+)?(?:(\d+)\s+)?"
        r"(second|minute|hour|day|week|month|year)",
        status_text or "",
        re.I,
    )
    if not match:
        return 0
    amount = int(match.group(1) or 1)
    return amount * UPTIME_UNITS[match.group(2).lower()]


def _duration_ns(value: Any) -> str:
    """Convert a nanosecond duration (docker healthcheck) to ``30s`` / ``5m``."""
    try:
        nanos = int(value)
    except (TypeError, ValueError):
        return ""
    if nanos <= 0:
        return ""
    seconds = nanos / 1e9
    if seconds >= 60:
        return f"{int(seconds // 60)}m"
    return f"{seconds:g}s"


def _as_list(value: Any) -> List[str]:
    """Coerce a docker command (str or list) into a list of arguments."""
    if not value:
        return []
    if isinstance(value, str):
        return shlex.split(value)
    return [str(item) for item in value]


def _entrypoint(value: Any) -> str:
    """Flatten a docker entrypoint (str or list) into a single string."""
    if not value:
        return ""
    if isinstance(value, str):
        return value
    return " ".join(str(item) for item in value)


# ── Host gauges ───────────────────────────────────────────────────────────────


def _host_cpu_pct(cores: int) -> float:
    """
    Aggregate host CPU usage (%).

    The daemon exposes no host-wide CPU percentage, so the 1-minute load
    average is normalised by the core count. It is a smoothed value, which is
    exactly what a gauge wants, and it costs nothing.
    """
    try:
        load1 = os.getloadavg()[0]
    except (OSError, AttributeError):
        return 0.0
    cores = cores or os.cpu_count() or 1
    return round(min(100.0, (load1 / cores) * 100), 1)


def _host_mem_used() -> int:
    """Used host memory in bytes (``MemTotal - MemAvailable`` when readable)."""
    try:
        entries: Dict[str, str] = {}
        with open("/proc/meminfo", "r", encoding="utf-8") as handle:
            for line in handle:
                key, _, value = line.partition(":")
                entries[key.strip()] = value.strip()
        total_kb = int(entries["MemTotal"].split()[0])
        available_kb = int(entries["MemAvailable"].split()[0])
        return max(0, total_kb - available_kb) * 1024
    except (OSError, KeyError, ValueError, IndexError):
        return 0


def _disk_usage(root: Optional[str]) -> Tuple[int, int]:
    """Return ``(total, used)`` bytes for the daemon root, falling back to ``/``."""
    for candidate in (root, "/"):
        if not candidate:
            continue
        try:
            usage = shutil.disk_usage(candidate)
            return int(usage.total), int(usage.used)
        except OSError:
            continue
    return 0, 0


def _build_host(config: InfraHostConfig, info: Dict[str, Any],
                version: Dict[str, Any]) -> InfraHost:
    """Compose an :class:`InfraHost` from ``/info`` + ``/version`` payloads."""
    cores = int(info.get("NCPU") or 0)
    mem_total = int(info.get("MemTotal") or 0)
    disk_total, disk_used = _disk_usage(info.get("DockerRootDir"))
    os_name = info.get("OperatingSystem") or info.get("OS") or ""
    platform_info = "/".join(
        part for part in (version.get("Os"), version.get("Arch")) if part
    )
    return InfraHost(
        id=config.id,
        name=config.name or info.get("Name") or config.id,
        endpoint=config.endpoint,
        engine=str(version.get("Version") or ""),
        os=f"{os_name} · {platform_info}".strip(" ·"),
        cpu_cores=cores,
        cpu_pct=_host_cpu_pct(cores),
        mem_total=mem_total,
        mem_used=_host_mem_used() if mem_total else 0,
        disk_total=disk_total,
        disk_used=disk_used,
        is_local=config.is_local,
    )


# ── Container field mappers ───────────────────────────────────────────────────


def _container_name(summary: Dict[str, Any]) -> str:
    names = summary.get("Names") or []
    return str(names[0]).lstrip("/") if names else ""


def _env_vars(env: Iterable[str]) -> List[InfraEnvVar]:
    """Map ``["K=V", …]`` env entries, masking secret-looking values."""
    variables: List[InfraEnvVar] = []
    for item in env or []:
        key, _, value = str(item).partition("=")
        if SECRET_KEY_PATTERN.search(key):
            value = "***"
        variables.append(InfraEnvVar(k=key, v=value))
    return variables


def _mount_from_payload(mount: Dict[str, Any]) -> InfraMount:
    """Map a docker mount entry (``Mounts`` or detail ``Mounts``)."""
    mount = mount or {}
    mode = mount.get("Mode") or ("rw" if mount.get("RW", True) else "ro")
    return InfraMount(
        type=mount.get("Type") or "bind",
        source=mount.get("Source") or mount.get("Name") or "",
        destination=mount.get("Destination") or "",
        mode=mode,
    )


def _network_attachments(payload: Dict[str, Any]) -> List[InfraNetworkAttachment]:
    """Map ``NetworkSettings.Networks`` into attachments."""
    networks = (payload.get("NetworkSettings") or {}).get("Networks") or {}
    return [
        InfraNetworkAttachment(name=name, ip=(config or {}).get("IPAddress") or "")
        for name, config in networks.items()
    ]


def _ports_from_summary(summary: Dict[str, Any]) -> List[InfraPort]:
    """Map the ``Ports`` array of ``/containers/json``."""
    ports: List[InfraPort] = []
    for port in summary.get("Ports") or []:
        public = (port or {}).get("PublicPort")
        ports.append(
            InfraPort(
                host=int(public) if public else None,
                container=int((port or {}).get("PrivatePort") or 0),
                proto=(port or {}).get("Type") or "tcp",
                published=bool(public),
            )
        )
    return ports


def _ports_from_detail(detail: Dict[str, Any]) -> List[InfraPort]:
    """Map ``NetworkSettings.Ports`` of a container inspect payload."""
    ports: List[InfraPort] = []
    bindings_by_port = (detail.get("NetworkSettings") or {}).get("Ports") or {}
    for spec, bindings in bindings_by_port.items():
        container_port, _, proto = str(spec).partition("/")
        proto = proto or "tcp"
        bindings = bindings or []
        if not bindings:
            ports.append(
                InfraPort(
                    host=None,
                    container=int(container_port or 0),
                    proto=proto,
                    published=False,
                )
            )
            continue
        for binding in bindings:
            host_port = (binding or {}).get("HostPort")
            ports.append(
                InfraPort(
                    host=int(host_port) if host_port else None,
                    container=int(container_port or 0),
                    proto=proto,
                    published=bool(host_port),
                )
            )
    return ports


def _health_from_status_text(status_text: str) -> Optional[str]:
    """Derive the health state from a ``docker ps`` STATUS string."""
    text = (status_text or "").lower()
    if "unhealthy" in text:
        return "unhealthy"
    if "healthy" in text:
        return "healthy"
    if "health: starting" in text or "starting" in text:
        return "starting"
    return None


def _health_from_detail(detail: Dict[str, Any]) -> Optional[str]:
    """Read ``State.Health.Status`` from a container inspect payload."""
    health = (detail.get("State") or {}).get("Health") or {}
    return health.get("Status") or None


def _healthcheck_from_detail(detail: Dict[str, Any]) -> Optional[InfraHealthcheck]:
    """Map ``Config.Healthcheck`` into :class:`InfraHealthcheck`."""
    check = (detail.get("Config") or {}).get("Healthcheck")
    if not check:
        return None
    test = check.get("Test") or []
    if isinstance(test, list) and len(test) > 1:
        command = " ".join(str(part) for part in test[1:])
    elif isinstance(test, list) and test:
        command = str(test[0])
    else:
        command = str(test or "")
    return InfraHealthcheck(
        test=command,
        interval=_duration_ns(check.get("Interval")),
        retries=int(check.get("Retries") or 0),
    )


def _is_sysbox(detail: Dict[str, Any], labels: Dict[str, str]) -> bool:
    """Return True when the container runs under the sysbox runtime."""
    runtime = str((detail.get("HostConfig") or {}).get("Runtime") or "")
    if runtime.startswith("sysbox"):
        return True
    return str((labels or {}).get("sysbox", "")).lower() in ("1", "true", "yes")


def _discover_url(ports: List[InfraPort], labels: Dict[str, str]) -> Optional[str]:
    """
    Best-effort public URL for a container.

    Order of preference:
    1. A Traefik rule label exposing a host name (``Host(`codx.local`)``).
    2. The first published port (``http://localhost:<port>``).
    """
    for key, value in (labels or {}).items():
        if not key.endswith(".rule"):
            continue
        match = re.search(r"Host\(\s*`([^`]+)`\s*\)", value or "")
        if match:
            return f"http://{match.group(1)}"

    for port in ports or []:
        if port.published and port.host:
            return f"http://localhost:{port.host}"
    return None


# ── Live usage (stats) ────────────────────────────────────────────────────────


def _cpu_percent(stats: Dict[str, Any]) -> float:
    """Compute the container CPU percentage from a one-shot stats payload."""
    cpu = stats.get("cpu_stats") or {}
    pre = stats.get("precpu_stats") or {}
    cpu_total = ((cpu.get("cpu_usage") or {}).get("total_usage") or 0)
    pre_total = ((pre.get("cpu_usage") or {}).get("total_usage") or 0)
    system_total = cpu.get("system_cpu_usage") or 0
    pre_system = pre.get("system_cpu_usage") or 0

    cpu_delta = cpu_total - pre_total
    system_delta = system_total - pre_system
    online_cpus = (
        cpu.get("online_cpus")
        or len((cpu.get("cpu_usage") or {}).get("percpu_usage") or [])
        or 1
    )
    if cpu_delta <= 0 or system_delta <= 0:
        return 0.0
    return round((cpu_delta / system_delta) * online_cpus * 100.0, 1)


def _memory_usage(stats: Dict[str, Any]) -> Tuple[int, int]:
    """Return ``(used, limit)`` bytes, excluding the page cache like docker does."""
    memory = stats.get("memory_stats") or {}
    usage = int(memory.get("usage") or 0)
    details = memory.get("stats") or {}
    cache = int(details.get("cache") or details.get("inactive_file") or 0)
    limit = int(memory.get("limit") or 0)
    return max(0, usage - cache), limit


def _network_usage(stats: Dict[str, Any]) -> Tuple[int, int]:
    """Return ``(rx, tx)`` totals summed over all interfaces."""
    rx = tx = 0
    for interface in (stats.get("networks") or {}).values():
        rx += int((interface or {}).get("rx_bytes") or 0)
        tx += int((interface or {}).get("tx_bytes") or 0)
    return rx, tx


def _block_usage(stats: Dict[str, Any]) -> Tuple[int, int]:
    """Return ``(read, write)`` block IO totals."""
    read = write = 0
    entries = (stats.get("blkio_stats") or {}).get("io_service_bytes_recursive") or []
    for entry in entries:
        operation = str((entry or {}).get("op") or "").lower()
        value = int((entry or {}).get("value") or 0)
        if operation == "read":
            read += value
        elif operation == "write":
            write += value
    return read, write


def _apply_stats(container: InfraContainer, stats: Dict[str, Any]) -> None:
    """Copy the live counters of a stats payload onto a container model."""
    container.cpu_pct = _cpu_percent(stats)
    mem_used, mem_limit = _memory_usage(stats)
    container.mem_used = mem_used
    if mem_limit:
        container.mem_limit = mem_limit
    container.mem_pct = (
        round((container.mem_used / container.mem_limit) * 100, 1)
        if container.mem_limit
        else 0.0
    )
    container.net_rx, container.net_tx = _network_usage(stats)
    container.block_read, container.block_write = _block_usage(stats)
    container.pids = int((stats.get("pids_stats") or {}).get("current") or 0)


# ── Container factories ───────────────────────────────────────────────────────


def _container_from_summary(summary: Dict[str, Any], host_id: str) -> InfraContainer:
    """Map one entry of ``/containers/json`` into :class:`InfraContainer`."""
    summary = summary or {}
    labels = summary.get("Labels") or {}
    status_text = summary.get("Status") or ""
    container_id = summary.get("Id") or ""
    uptime = _uptime_from_status(status_text)
    ports = _ports_from_summary(summary)

    return InfraContainer(
        id=container_id,
        short=container_id[:12],
        name=_container_name(summary),
        image=summary.get("Image") or "",
        image_id=summary.get("ImageID") or "",
        state=summary.get("State") or "unknown",
        health=_health_from_status_text(status_text),
        status_text=status_text,
        created=_iso(summary.get("Created")),
        started_at=_iso(time.time() - uptime) if uptime else "",
        uptime_seconds=uptime,
        host_id=host_id,
        stack=labels.get(COMPOSE_PROJECT_LABEL, ""),
        service=labels.get(COMPOSE_SERVICE_LABEL, ""),
        ports=ports,
        labels=labels,
        mounts=[_mount_from_payload(mount) for mount in summary.get("Mounts") or []],
        networks=_network_attachments(summary),
        url=_discover_url(ports, labels),
    )


def _container_from_detail(detail: Dict[str, Any], host_id: str) -> InfraContainer:
    """Map a ``/containers/{id}/json`` payload into :class:`InfraContainer`."""
    detail = detail or {}
    config = detail.get("Config") or {}
    state = detail.get("State") or {}
    host_config = detail.get("HostConfig") or {}
    labels = config.get("Labels") or {}

    container_id = detail.get("Id") or ""
    state_name = state.get("Status") or "unknown"
    started_at = _iso(state.get("StartedAt"))
    uptime = (
        max(0, int(time.time() - datetime.fromisoformat(started_at).timestamp()))
        if state_name == "running" and started_at
        else 0
    )
    ports = _ports_from_detail(detail)

    return InfraContainer(
        id=container_id,
        short=container_id[:12],
        name=str(detail.get("Name") or "").lstrip("/"),
        image=config.get("Image") or "",
        image_id=detail.get("Image") or "",
        state=state_name,
        health=_health_from_detail(detail),
        status_text=_status_text(state_name, uptime, state.get("ExitCode")),
        created=_iso(detail.get("Created")),
        started_at=started_at,
        uptime_seconds=uptime,
        host_id=host_id,
        stack=labels.get(COMPOSE_PROJECT_LABEL, ""),
        service=labels.get(COMPOSE_SERVICE_LABEL, ""),
        ports=ports,
        mem_limit=int(host_config.get("Memory") or 0),
        restart_count=int(detail.get("RestartCount") or 0),
        restart_policy=(host_config.get("RestartPolicy") or {}).get("Name") or "",
        labels=labels,
        env=_env_vars(config.get("Env") or []),
        mounts=[_mount_from_payload(mount) for mount in detail.get("Mounts") or []],
        networks=_network_attachments(detail),
        cmd=_as_list(config.get("Cmd")),
        entrypoint=_entrypoint(config.get("Entrypoint")),
        healthcheck=_healthcheck_from_detail(detail),
        url=_discover_url(ports, labels),
        sysbox=_is_sysbox(detail, labels),
    )


def _parse_log_lines(text: str) -> List[InfraLogLine]:
    """Split a log stream into timestamped, level-tagged lines."""
    lines: List[InfraLogLine] = []
    for raw_line in (text or "").splitlines():
        if not raw_line.strip():
            continue
        timestamp, _, message = raw_line.partition(" ")
        level_match = LOG_LEVEL_RE.search(message or "")
        level = (level_match.group(1) if level_match else "INFO").upper()
        if level == "WARNING":
            level = "WARN"
        elif level == "CRITICAL":
            level = "FATAL"
        lines.append(
            InfraLogLine(ts=_iso(timestamp) or timestamp, level=level, msg=message.strip())
        )
    return lines


def _create_body(payload: InfraCreateContainerRequest) -> Dict[str, Any]:
    """Build the ``POST /containers/create`` body from the API request."""
    ports = [port for port in payload.ports if port and port.container]
    env = [f"{variable.k}={variable.v}" for variable in payload.env if variable and variable.k]
    command = shlex.split(payload.cmd) if (payload.cmd or "").strip() else None

    exposed_ports = {f"{port.container}/{port.proto or 'tcp'}": {} for port in ports}
    port_bindings: Dict[str, List[Dict[str, str]]] = {}
    for port in ports:
        if port.host:
            spec = f"{port.container}/{port.proto or 'tcp'}"
            port_bindings.setdefault(spec, []).append({"HostPort": str(port.host)})

    labels: Dict[str, str] = {}
    if payload.stack:
        labels[COMPOSE_PROJECT_LABEL] = payload.stack
        labels[COMPOSE_SERVICE_LABEL] = payload.name

    body: Dict[str, Any] = {
        "Image": payload.image,
        "Env": env,
        "Labels": labels,
        "HostConfig": {"RestartPolicy": {"Name": "unless-stopped"}},
    }
    if command:
        body["Cmd"] = command
    if exposed_ports:
        body["ExposedPorts"] = exposed_ports
    if port_bindings:
        body["HostConfig"]["PortBindings"] = port_bindings
    return body


def _stack_from_volume_name(name: str) -> str:
    """Infer the compose project from a volume name (``project_volume``)."""
    if not name or ANONYMOUS_VOLUME_RE.match(name) or "_" not in name:
        return ""
    return name.split("_", 1)[0]


# ── Maintenance helpers ───────────────────────────────────────────────────────


def _until_filter(older_than_days: Optional[int]) -> Optional[str]:
    """
    Convert ``older_than_days`` into a docker duration filter (``"48h"``).

    Returns ``None`` when no window is requested (``None`` or ``0``), which
    means "no age restriction".

    Example:
        >>> _until_filter(2)
        '48h'
        >>> _until_filter(None) is None
        True
    """
    try:
        days = int(older_than_days or 0)
    except (TypeError, ValueError):
        return None
    if days <= 0:
        return None
    return f"{days * 24}h"


def _filters_param(filters: Dict[str, List[str]]) -> str:
    """
    Encode a filter map the way the Engine API expects it.

    Docker takes ``filters`` as a compact JSON object whose values are always
    arrays, e.g. ``{"dangling":["true"],"until":["48h"]}``.

    Example:
        >>> _filters_param({"dangling": ["true"]})
        '{"dangling":["true"]}'
    """
    cleaned = {
        key: [str(value) for value in values]
        for key, values in (filters or {}).items()
        if values
    }
    return json.dumps(cleaned, separators=(",", ":"))


def _prune_result(payload: Any, host_id: str, target: str) -> InfraPruneResult:
    """
    Normalise a ``*/prune`` response into :class:`InfraPruneResult`.

    The daemon answers with different keys per resource class
    (``ImagesDeleted``, ``VolumesDeleted``, ``NetworksDeleted``,
    ``CachesDeleted``, ``ContainersDeleted``) plus a shared
    ``SpaceReclaimed`` counter, so the removal count is aggregated generically
    instead of being hard-coded per target.
    """
    payload = payload or {}
    removed = 0
    for key, value in payload.items():
        if str(key).lower().endswith("deleted") and isinstance(value, list):
            removed += len(value)
    return InfraPruneResult(
        ok=True,
        host_id=host_id,
        target=target,
        removed=removed,
        reclaimed_bytes=max(0, int(payload.get("SpaceReclaimed") or 0)),
    )


# ── Manager ───────────────────────────────────────────────────────────────────


class InfraManager:
    """Read/write access to Docker hosts, shaped for the `/api/infra/*` API."""

    def __init__(self, hosts: Optional[List[InfraHostConfig]] = None):
        self._hosts: List[InfraHostConfig] = hosts or _default_hosts()
        self._clients: Dict[str, DockerClient] = {}
        self._clients_lock = threading.Lock()
        self._series: Dict[Tuple[str, str], List[Dict[str, Any]]] = {}
        self._series_lock = threading.Lock()

    # -- host registry -----------------------------------------------------

    def host_config(self, host_id: Optional[str] = None) -> InfraHostConfig:
        """
        Resolve a host id (``None`` picks the first configured host).

        Raises:
            KeyError: The host id is unknown.
        """
        if host_id:
            for host in self._hosts:
                if host.id == host_id:
                    return host
            raise KeyError(host_id)
        return self._hosts[0]

    def client(self, host_id: Optional[str] = None) -> DockerClient:
        """Return a cached :class:`DockerClient` for the given host."""
        host = self.host_config(host_id)
        with self._clients_lock:
            client = self._clients.get(host.id)
            if client is None:
                client = DockerClient(endpoint=host.endpoint)
                self._clients[host.id] = client
            return client

    def host(self, host_id: Optional[str] = None) -> InfraHost:
        """Describe a single host (gauges come from ``/info`` + ``/version``)."""
        config = self.host_config(host_id)
        info: Dict[str, Any] = {}
        version: Dict[str, Any] = {}
        try:
            client = self.client(config.id)
            info = client.get_json("/info")
            version = client.get_json("/version")
        except (DockerUnavailable, DockerAPIError) as ex:
            logger.warning("Docker host %s unavailable: %s", config.id, ex)
        return _build_host(config, info, version)

    def hosts(self) -> InfraHostList:
        """List every configured host."""
        return InfraHostList(hosts=[self.host(host.id) for host in self._hosts])

    # -- containers --------------------------------------------------------

    def containers(
        self,
        host_id: Optional[str] = None,
        state: Optional[str] = None,
        stack: Optional[str] = None,
        query: Optional[str] = None,
        with_stats: bool = True,
    ) -> InfraContainerList:
        """
        List containers, optionally with live CPU/memory usage.

        Args:
            host_id: Target host (defaults to the first configured one).
            state: ``running``/``exited``/… or ``unhealthy``/``all``.
            stack: Compose project name, or ``all``.
            query: Case-insensitive substring over name/image/stack/service.
            with_stats: Read one ``/stats`` per running container (slower).
        """
        client = self.client(host_id)
        resolved_host = self.host_config(host_id).id

        summaries = client.get_json("/containers/json", params={"all": "true"})
        containers = [
            _container_from_summary(summary, resolved_host)
            for summary in summaries or []
        ]

        if with_stats:
            self._attach_stats(client, containers)

        filtered = self._filter_containers(containers, state=state, stack=stack, query=query)
        return InfraContainerList(total=len(filtered), containers=filtered)

    @staticmethod
    def _filter_containers(
        containers: List[InfraContainer],
        state: Optional[str] = None,
        stack: Optional[str] = None,
        query: Optional[str] = None,
    ) -> List[InfraContainer]:
        """Apply the ``state``/``stack``/``q`` filters used by the UI."""
        result = containers
        if state and state != "all":
            if state == "unhealthy":
                result = [item for item in result if item.health == "unhealthy"]
            else:
                result = [item for item in result if item.state == state]

        if stack and stack != "all":
            result = [item for item in result if item.stack == stack]

        term = (query or "").strip().lower()
        if term:
            result = [
                item
                for item in result
                if term in (item.name or "").lower()
                or term in (item.image or "").lower()
                or term in (item.service or "").lower()
                or term in (item.stack or "").lower()
            ]
        return result

    def _attach_stats(self, client: DockerClient, containers: List[InfraContainer]) -> None:
        """Fill live counters for every *running* container, in parallel."""
        running = [item for item in containers if item.state == "running"]
        if not running:
            return

        with ThreadPoolExecutor(max_workers=STATS_POOL_SIZE) as pool:
            payloads = list(pool.map(lambda item: self._safe_stats(client, item.id), running))

        for container, payload in zip(running, payloads):
            if payload:
                _apply_stats(container, payload)

    @staticmethod
    def _safe_stats(client: DockerClient, container_id: str) -> Optional[Dict[str, Any]]:
        """Read one stats sample; a failure must not break the whole listing."""
        try:
            return client.get_json(
                f"/containers/{container_id}/stats", params={"stream": "false"}
            )
        except (DockerUnavailable, DockerAPIError) as ex:
            logger.debug("Cannot read stats for %s: %s", container_id, ex)
            return None

    def container(self, container_id: str, host_id: Optional[str] = None) -> InfraContainer:
        """Return the full inspect payload of a container."""
        client = self.client(host_id)
        detail = client.get_json(f"/containers/{container_id}/json")
        return _container_from_detail(detail, self.host_config(host_id).id)

    def logs(
        self, container_id: str, tail: int = 200, host_id: Optional[str] = None
    ) -> InfraContainerLogs:
        """
        Return the last ``tail`` log lines of a container.

        Args:
            container_id: Container id or name.
            tail: Number of lines (clamped to 1..2000).
            host_id: Target host.
        """
        tail = max(1, min(int(tail or 200), 2000))
        raw = self.client(host_id).get_bytes(
            f"/containers/{container_id}/logs",
            params={"stdout": "1", "stderr": "1", "timestamps": "1", "tail": str(tail)},
        )
        return InfraContainerLogs(
            id=container_id, lines=_parse_log_lines(demux_frame_stream(raw))
        )

    def stats(self, container_id: str, host_id: Optional[str] = None) -> InfraStats:
        """
        Return current counters plus the in-process CPU/memory series.

        The daemon only exposes an instantaneous sample, so the series is a
        ring buffer (last :data:`SERIES_LENGTH` polls) that fills as the UI
        polls this endpoint.
        """
        resolved_host = self.host_config(host_id).id
        payload = self.client(host_id).get_json(
            f"/containers/{container_id}/stats", params={"stream": "false"}
        )

        probe = InfraContainer(id=container_id)
        _apply_stats(probe, payload)

        point = {
            "t": datetime.now(timezone.utc).isoformat(),
            "cpu": probe.cpu_pct,
            "mem": probe.mem_used,
        }
        series = self._push_series(resolved_host, container_id, point)

        return InfraStats(
            current=InfraStatsCurrent(
                cpu_pct=probe.cpu_pct,
                mem_used=probe.mem_used,
                mem_limit=probe.mem_limit,
                net_rx=probe.net_rx,
                net_tx=probe.net_tx,
                block_read=probe.block_read,
                block_write=probe.block_write,
                pids=probe.pids,
            ),
            series=[InfraStatsPoint(**entry) for entry in series],
        )

    def _push_series(
        self, host_id: str, container_id: str, point: Dict[str, Any]
    ) -> List[Dict[str, Any]]:
        """Append a sample to the container ring buffer and return the buffer."""
        key = (host_id, container_id)
        with self._series_lock:
            series = self._series.setdefault(key, [])
            series.append(point)
            del series[:-SERIES_LENGTH]
            return list(series)

    def action(
        self, container_id: str, request: InfraActionRequest, host_id: Optional[str] = None
    ) -> InfraContainer:
        """
        Run a lifecycle action and return the refreshed container.

        Raises:
            ValueError: The action is not supported.
        """
        action = (request.action or "").strip().lower()
        if action not in VALID_ACTIONS:
            raise ValueError(
                f"Unsupported action '{request.action}'. "
                f"Allowed: {', '.join(VALID_ACTIONS)}"
            )

        client = self.client(host_id)
        params = {"t": "10"} if action in ("stop", "restart") else None
        client.post(f"/containers/{container_id}/{action}", params=params)
        logger.info("Container %s action '%s' completed", container_id, action)
        return self.container(container_id, host_id)

    def create_container(
        self, payload: InfraCreateContainerRequest, host_id: Optional[str] = None
    ) -> InfraContainer:
        """
        Create and start a container, then return it.

        Raises:
            ValueError: ``name`` or ``image`` is missing.
            DockerAPIError: The daemon refused the create/start call.
        """
        name = (payload.name or "").strip()
        image = (payload.image or "").strip()
        if not name or not image:
            raise ValueError("Both 'name' and 'image' are required")

        target_host = payload.host_id or host_id
        client = self.client(target_host)

        created = client.post(
            "/containers/create", params={"name": name}, json_body=_create_body(payload)
        )
        container_id = created.get("Id")
        if not container_id:
            raise DockerAPIError(
                500, "The daemon did not return a container id", "/containers/create"
            )

        client.post(f"/containers/{container_id}/start")
        logger.info("Container %s ('%s') created from image %s", container_id, name, image)
        return self.container(container_id, target_host)

    def remove_container(
        self, container_id: str, host_id: Optional[str] = None
    ) -> InfraOk:
        """Remove a (possibly running) container."""
        self.client(host_id).delete(
            f"/containers/{container_id}", params={"force": "1"}
        )
        logger.info("Container %s removed", container_id)
        return InfraOk(ok=True)

    # -- host summary ------------------------------------------------------

    def summary(self, host_id: Optional[str] = None) -> InfraSummary:
        """Host gauges plus container/image/volume/network counts."""
        host = self.host(host_id)
        containers = self.containers(host.id, with_stats=False).containers
        images = self.images(host.id).images
        volumes = self.volumes(host.id).volumes
        networks = self.networks(host.id).networks

        counts = InfraSummaryCounts(
            total=len(containers),
            running=sum(1 for item in containers if item.state == "running"),
            stopped=sum(1 for item in containers if item.state in ("exited", "created")),
            paused=sum(1 for item in containers if item.state == "paused"),
            restarting=sum(1 for item in containers if item.state == "restarting"),
            unhealthy=sum(1 for item in containers if item.health == "unhealthy"),
            images=sum(1 for image in images if not image.dangling),
            volumes=len(volumes),
            networks=len(networks),
        )

        return InfraSummary(
            host=host,
            engine=host.engine,
            cpu_pct=host.cpu_pct,
            cpu_cores=host.cpu_cores,
            mem_used=host.mem_used,
            mem_total=host.mem_total,
            disk_used=host.disk_used,
            disk_total=host.disk_total,
            counts=counts,
        )

    # -- compose stacks ----------------------------------------------------

    def stacks(self, host_id: Optional[str] = None) -> InfraStackList:
        """Group containers by their compose project labels."""
        resolved_host = self.host_config(host_id).id
        containers = self.containers(resolved_host, with_stats=False).containers

        groups: Dict[str, Dict[str, Any]] = {}
        for container in containers:
            if not container.stack:
                continue
            group = groups.setdefault(
                container.stack,
                {"name": container.stack, "path": "", "services": []},
            )
            group["services"].append(
                InfraStackService(
                    service=container.service,
                    name=container.name,
                    state=container.state,
                    health=container.health,
                    id=container.id,
                )
            )
            group["path"] = group["path"] or (
                container.labels.get(COMPOSE_CONFIG_LABEL)
                or container.labels.get(COMPOSE_WORKDIR_LABEL)
                or ""
            )

        stacks: List[InfraStack] = []
        for group in sorted(groups.values(), key=lambda item: item["name"]):
            total = len(group["services"])
            running = sum(1 for service in group["services"] if service.state == "running")
            status = "running" if running == total else ("stopped" if running == 0 else "degraded")
            stacks.append(
                InfraStack(
                    name=group["name"],
                    host_id=resolved_host,
                    path=group["path"],
                    status=status,
                    running=running,
                    total=total,
                    services=group["services"],
                )
            )
        return InfraStackList(stacks=stacks)

    # -- images / volumes / networks ---------------------------------------

    def images(self, host_id: Optional[str] = None) -> InfraImageList:
        """List images with the number of containers using each one."""
        client = self.client(host_id)

        raw_images = client.get_json("/images/json", params={"all": "false"})
        raw_containers = client.get_json("/containers/json", params={"all": "true"})

        usage: Dict[str, int] = {}
        for container in raw_containers or []:
            image_id = (container or {}).get("ImageID") or ""
            usage[image_id] = usage.get(image_id, 0) + 1

        images: List[InfraImage] = []
        for image in raw_images or []:
            image = image or {}
            image_id = image.get("Id") or ""
            size = int(image.get("Size") or 0)
            created = _iso(image.get("Created"))
            tags = image.get("RepoTags") or []

            if not tags or tags == ["<none>:<none>"]:
                images.append(
                    InfraImage(
                        repo="<none>",
                        tag="<none>",
                        id=image_id,
                        size=size,
                        created=created,
                        containers=usage.get(image_id, 0),
                        dangling=True,
                    )
                )
                continue

            for tag in tags:
                repo, _, version = str(tag).rpartition(":")
                images.append(
                    InfraImage(
                        repo=repo or str(tag),
                        tag=version or "latest",
                        id=image_id,
                        size=size,
                        created=created,
                        containers=usage.get(image_id, 0),
                        dangling=False,
                    )
                )

        images.sort(key=lambda item: (item.repo, item.tag))
        return InfraImageList(images=images)

    def volumes(self, host_id: Optional[str] = None) -> InfraVolumeList:
        """List volumes with usage, owner stack and anonymity flags."""
        client = self.client(host_id)

        payload = client.get_json("/volumes")
        raw_containers = client.get_json("/containers/json", params={"all": "true"})

        in_use = set()
        for container in raw_containers or []:
            for mount in (container or {}).get("Mounts") or []:
                if (mount or {}).get("Type") == "volume" and (mount or {}).get("Name"):
                    in_use.add(mount["Name"])

        volumes: List[InfraVolume] = []
        for volume in (payload or {}).get("Volumes") or []:
            volume = volume or {}
            name = volume.get("Name") or ""
            size = int(((volume.get("UsageData") or {}).get("Size")) or 0)
            volumes.append(
                InfraVolume(
                    name=name,
                    driver=volume.get("Driver") or "",
                    scope=volume.get("Scope") or "local",
                    mountpoint=volume.get("Mountpoint") or "",
                    size=max(0, size),
                    stack=_stack_from_volume_name(name),
                    in_use=name in in_use,
                    anonymous=ANONYMOUS_VOLUME_RE.match(name) is not None,
                    created=_iso(volume.get("CreatedAt")),
                )
            )

        volumes.sort(key=lambda item: item.name)
        return InfraVolumeList(volumes=volumes)

    def networks(self, host_id: Optional[str] = None) -> InfraNetworkList:
        """List networks with subnet and connected containers."""
        raw_networks = self.client(host_id).get_json("/networks")

        networks: List[InfraNetwork] = []
        for network in raw_networks or []:
            network = network or {}
            configs = (network.get("IPAM") or {}).get("Config") or []
            subnet = (configs[0] or {}).get("Subnet") if configs else ""
            attached = {
                (entry or {}).get("Name") or ""
                for entry in (network.get("Containers") or {}).values()
                if entry
            }
            networks.append(
                InfraNetwork(
                    id=network.get("Id") or "",
                    name=network.get("Name") or "",
                    driver=network.get("Driver") or "",
                    scope=network.get("Scope") or "local",
                    subnet=subnet or "—",
                    internal=bool(network.get("Internal")),
                    containers=sorted(name for name in attached if name),
                    created=_iso(network.get("Created")),
                )
            )

        networks.sort(key=lambda item: item.name)
        return InfraNetworkList(networks=networks)

    # -- maintenance: single resource removal ------------------------------

    def remove_image(self, image_id: str, host_id: Optional[str] = None) -> InfraOk:
        """
        Remove an image by id (``sha256:…``) or ``repo:tag`` reference.

        Args:
            image_id: Image id or tag reference.
            host_id: Target host.

        Raises:
            ValueError: The reference is empty.
            DockerAPIError: HTTP 409 (or 500 on older engines) while a
                container still references the image.
        """
        reference = (image_id or "").strip()
        if not reference:
            raise ValueError("An image id or 'repo:tag' reference is required")

        # ``/``, ``:`` and ``@`` are valid in an image reference, so they are
        # kept readable in the path instead of being percent-encoded.
        self.client(host_id).delete(f"/images/{quote(reference, safe='/:@')}")
        logger.info("Image %s removed", reference)
        return InfraOk(ok=True)

    def remove_volume(self, name: str, host_id: Optional[str] = None) -> InfraOk:
        """
        Remove a volume by name.

        Args:
            name: Volume name.
            host_id: Target host.

        Raises:
            ValueError: The name is empty.
            DockerAPIError: HTTP 409 while a container mounts the volume.
        """
        volume_name = (name or "").strip()
        if not volume_name:
            raise ValueError("A volume name is required")

        self.client(host_id).delete(f"/volumes/{quote(volume_name, safe='')}")
        logger.info("Volume %s removed", volume_name)
        return InfraOk(ok=True)

    def remove_network(self, network_id: str, host_id: Optional[str] = None) -> InfraOk:
        """
        Remove a network by id or name.

        Args:
            network_id: Network id or name.
            host_id: Target host.

        Raises:
            ValueError: The reference is empty.
            DockerAPIError: HTTP 403 for predefined networks (``bridge``,
                ``host``, ``none``) or 409 while endpoints remain attached.
        """
        reference = (network_id or "").strip()
        if not reference:
            raise ValueError("A network id or name is required")

        self.client(host_id).delete(f"/networks/{quote(reference, safe='')}")
        logger.info("Network %s removed", reference)
        return InfraOk(ok=True)

    # -- maintenance: prune ------------------------------------------------

    def prune(
        self, request: InfraPruneRequest, host_id: Optional[str] = None
    ) -> InfraPruneResult:
        """
        Prune one resource class and report what was reclaimed.

        Target mapping (Engine API):

        ==============  =========================================================
        ``target``      Daemon call
        ==============  =========================================================
        ``images``      ``POST /images/prune`` (``dangling`` + ``until`` filters)
        ``volumes``     ``POST /volumes/prune`` (``all=true`` unless dangling)
        ``networks``    ``POST /networks/prune``
        ``build_cache`` ``POST /build/prune?all=true`` (``until`` filter)
        ``system``      ``POST /system/prune`` (volumes excluded, docker default)
        ==============  =========================================================

        ``system`` also removes **stopped containers**, which is docker's
        definition of a system prune; named volumes are intentionally kept
        because dropping them would lose data.

        Args:
            request: Prune options (``target``, ``older_than_days``,
                ``dangling_only``, ``host_id``).
            host_id: Target host (``request.host_id`` wins when set).

        Returns:
            :class:`InfraPruneResult` with ``removed`` and ``reclaimed_bytes``.

        Raises:
            ValueError: The target is not supported.
        """
        target = (request.target or "").strip().lower()
        if target not in VALID_PRUNE_TARGETS:
            raise ValueError(
                f"Unsupported prune target '{request.target}'. "
                f"Allowed: {', '.join(VALID_PRUNE_TARGETS)}"
            )

        target_host = request.host_id or host_id
        resolved_host = self.host_config(target_host).id
        client = self.client(target_host)
        until = _until_filter(request.older_than_days)

        if target == "images":
            filters: Dict[str, List[str]] = {
                "dangling": ["true" if request.dangling_only else "false"]
            }
            if until:
                filters["until"] = [until]
            payload = client.post(
                "/images/prune", params={"filters": _filters_param(filters)}
            )
        elif target == "volumes":
            # docker default only prunes anonymous volumes; ``all=true`` also
            # drops unused named volumes (what the maintenance view lists).
            params = None if request.dangling_only else {
                "filters": _filters_param({"all": ["true"]})
            }
            payload = client.post("/volumes/prune", params=params)
        elif target == "networks":
            payload = client.post("/networks/prune")
        elif target == "build_cache":
            params = {"all": "true"}
            if until:
                params["filters"] = _filters_param({"until": [until]})
            payload = client.post("/build/prune", params=params)
        else:  # system
            payload = client.post("/system/prune", params={"volumes": "false"})

        result = _prune_result(payload, resolved_host, target)
        logger.info(
            "Prune '%s' on %s removed %d resource(s), reclaimed %d bytes",
            target,
            resolved_host,
            result.removed,
            result.reclaimed_bytes,
        )
        return result

    # -- events ------------------------------------------------------------

    def events(
        self, host_id: Optional[str] = None, minutes: int = EVENTS_WINDOW_MINUTES
    ) -> InfraEventList:
        """
        Return recent daemon events, newest first.

        The window is closed (``until = now``) so the stream terminates and the
        body can be read in one shot.

        Args:
            host_id: Target host.
            minutes: How far back to look (clamped to >= 1 minute).
        """
        now = time.time()
        window = max(1, int(minutes or EVENTS_WINDOW_MINUTES))
        params = {"since": str(int(now - window * 60)), "until": str(int(now))}

        events: List[InfraEvent] = []
        for item in self.client(host_id).iter_json_lines("/events", params=params):
            item = item or {}
            timestamp = item.get("time")
            if timestamp is None and item.get("timeNano"):
                timestamp = item["timeNano"] / 1e9
            actor = item.get("Actor") or {}
            attributes = actor.get("Attributes") or {}
            events.append(
                InfraEvent(
                    ts=_iso(timestamp),
                    type=item.get("Type") or item.get("type") or "",
                    action=item.get("Action") or item.get("status") or "",
                    actor=attributes.get("name") or str(actor.get("ID") or "")[:12],
                )
            )

        events.sort(key=lambda item: item.ts, reverse=True)
        return InfraEventList(events=events[:100])


# ── Singleton ─────────────────────────────────────────────────────────────────

_infra_manager: Optional[InfraManager] = None
_infra_manager_lock = threading.Lock()


def get_infra_manager() -> InfraManager:
    """
    Return the process-wide :class:`InfraManager` (lazily created).

    Lazy creation keeps module import (router auto-discovery) independent from
    the daemon being reachable.
    """
    global _infra_manager
    if _infra_manager is None:
        with _infra_manager_lock:
            if _infra_manager is None:
                _infra_manager = InfraManager()
    return _infra_manager

